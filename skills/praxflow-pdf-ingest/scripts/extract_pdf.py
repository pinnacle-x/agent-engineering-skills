#!/usr/bin/env python3
"""Extract PDF text and optional page images into PraxFlow traceable artifacts.

The helper preserves the existing text-first workflow while adding a visual path
for schematics, drawings, scans, diagrams, and other layout-dependent pages.
It does not run OCR or perform semantic interpretation.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Iterable


@dataclass
class PageResult:
    page: int
    method: str
    chars: int
    status: str
    notes: list[str]
    image: str | None = None


def _extract_with_pymupdf(pdf: Path) -> list[str]:
    import fitz  # type: ignore

    doc = fitz.open(pdf)
    try:
        return [page.get_text("text") or "" for page in doc]
    finally:
        doc.close()


def _extract_with_pypdf(pdf: Path) -> list[str]:
    from pypdf import PdfReader  # type: ignore

    reader = PdfReader(str(pdf))
    return [(page.extract_text() or "") for page in reader.pages]


def choose_extractor() -> tuple[str, Callable[[Path], list[str]]]:
    try:
        import fitz  # noqa: F401

        return "pymupdf", _extract_with_pymupdf
    except Exception:
        pass

    try:
        import pypdf  # noqa: F401

        return "pypdf", _extract_with_pypdf
    except Exception as exc:
        raise RuntimeError(
            "No supported PDF extractor is installed. Install PyMuPDF "
            "(`python -m pip install pymupdf`) or pypdf "
            "(`python -m pip install pypdf`)."
        ) from exc


def normalize_text(text: str) -> str:
    lines = [
        line.rstrip()
        for line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    ]
    return "\n".join(lines).strip()


def page_status(text: str) -> tuple[str, list[str]]:
    notes: list[str] = []
    if len(text) < 20:
        notes.append("Very little extractable text; inspect the page image and consider OCR.")
        return "OCR_CANDIDATE", notes
    return "EXTRACTED", notes


def render_pages(
    pdf: Path,
    image_dir: Path,
    dpi: int,
    selected_pages: set[int] | None,
) -> dict[int, Path]:
    try:
        import fitz  # type: ignore
    except Exception as exc:
        raise RuntimeError(
            "Page rendering requires PyMuPDF. Install it with "
            "`python -m pip install pymupdf`."
        ) from exc

    image_dir.mkdir(parents=True, exist_ok=True)
    doc = fitz.open(pdf)
    rendered: dict[int, Path] = {}
    try:
        scale = dpi / 72.0
        matrix = fitz.Matrix(scale, scale)
        for index, page in enumerate(doc, start=1):
            if selected_pages is not None and index not in selected_pages:
                continue
            pix = page.get_pixmap(matrix=matrix, alpha=False)
            path = image_dir / f"page_{index:03d}.png"
            pix.save(path)
            rendered[index] = path
    finally:
        doc.close()
    return rendered


def build_raw(
    pdf: Path,
    pages: Iterable[str],
    rendered: dict[int, Path],
    out_dir: Path,
) -> tuple[str, list[PageResult]]:
    out: list[str] = [
        f"# Raw extraction: {pdf.name}",
        "",
        "> Generated by PraxFlow PDF ingestion. Treat this as evidence, not an implementation specification.",
        "",
    ]
    results: list[PageResult] = []

    for index, original in enumerate(pages, start=1):
        text = normalize_text(original)
        status, notes = page_status(text)
        image_path = rendered.get(index)
        image_rel: str | None = None
        if image_path is not None:
            try:
                image_rel = image_path.relative_to(out_dir).as_posix()
            except ValueError:
                image_rel = image_path.as_posix()
            notes.append(f"Rendered page image: {image_rel}")

        results.append(
            PageResult(
                page=index,
                method="text-layer",
                chars=len(text),
                status=status,
                notes=notes,
                image=image_rel,
            )
        )

        out.extend(
            [
                "---",
                "",
                f"<!-- source_file: {pdf.name} -->",
                f"<!-- source_page: {index} -->",
                "",
                f"## Page {index}",
                "",
            ]
        )
        if image_rel:
            out.extend(
                [
                    f"<!-- source_page_image: {image_rel} -->",
                    f"Visual artifact: `{image_rel}`",
                    "",
                ]
            )
        out.extend(
            [
                text
                if text
                else "TODO_VERIFY: No reliable text extracted from this page. Inspect the source page image; OCR may be required.",
                "",
            ]
        )

    return "\n".join(out).rstrip() + "\n", results


def build_report(
    pdf: Path,
    extractor_name: str,
    results: list[PageResult],
    render_mode: str,
    dpi: int,
) -> str:
    ocr_candidates = [r.page for r in results if r.status == "OCR_CANDIDATE"]
    failed = [r.page for r in results if r.status == "FAILED"]
    rendered_pages = [r.page for r in results if r.image]
    overall = "PASS"
    if failed:
        overall = "BLOCKED"
    elif ocr_candidates:
        overall = "PASS_WITH_WARNINGS"

    lines = [
        f"# Extraction report: {pdf.name}",
        "",
        f"- Extractor: `{extractor_name}`",
        f"- Total pages: {len(results)}",
        f"- OCR candidates: {len(ocr_candidates)}",
        f"- Render mode: `{render_mode}`",
        f"- Render DPI: {dpi if render_mode != 'none' else 'n/a'}",
        f"- Rendered page images: {len(rendered_pages)}",
        f"- Failed pages: {len(failed)}",
        f"- Overall result: **{overall}**",
        "",
    ]

    if rendered_pages:
        lines.extend(
            [
                "## Visual artifacts",
                "",
                "Use these page images when layout, connectivity, symbols, diagrams, tables, or spatial relationships carry meaning.",
                "",
            ]
        )
        for r in results:
            if r.image:
                lines.append(f"- Page {r.page}: `{r.image}`")
        lines.append("")

    if ocr_candidates:
        lines.extend(["## OCR candidates", "", ", ".join(map(str, ocr_candidates)), ""])

    lines.extend(
        [
            "## Page details",
            "",
            "| Page | Method | Characters | Status | Image | Notes |",
            "|---:|---|---:|---|---|---|",
        ]
    )
    for r in results:
        notes = "; ".join(r.notes).replace("|", "\\|")
        image = (r.image or "").replace("|", "\\|")
        lines.append(
            f"| {r.page} | {r.method} | {r.chars} | {r.status} | {image} | {notes} |"
        )

    lines.extend(
        [
            "",
            "## Next action",
            "",
            "For schematics/drawings, inspect every rendered page with a vision-capable model or human reviewer. "
            "For OCR candidates, use OCR only when text is required and the visual inspection is insufficient. "
            "Do not infer electrical connectivity from extracted labels alone when the page image or a netlist is available.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Extract a PDF into PraxFlow raw Markdown and optional page images."
    )
    parser.add_argument("pdf", type=Path)
    parser.add_argument("--out-dir", type=Path, default=Path("docs/raw"))
    parser.add_argument(
        "--render-images",
        choices=("none", "candidates", "all"),
        default="candidates",
        help=(
            "Render no pages, OCR-candidate pages only, or every page. "
            "Use 'all' for schematics/drawings because connectivity is visual."
        ),
    )
    parser.add_argument(
        "--schematic",
        action="store_true",
        help="Shortcut for --render-images all; intended for schematics and engineering drawings.",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=180,
        help="PNG render resolution. Default: 180 DPI.",
    )
    parser.add_argument("--json", action="store_true", help="Print machine-readable result summary.")
    args = parser.parse_args()

    pdf = args.pdf
    if not pdf.is_file() or pdf.suffix.lower() != ".pdf":
        parser.error(f"Not a PDF file: {pdf}")
    if args.dpi < 72 or args.dpi > 600:
        parser.error("--dpi must be between 72 and 600")

    render_mode = "all" if args.schematic else args.render_images

    try:
        extractor_name, extractor = choose_extractor()
        pages = extractor(pdf)
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    args.out_dir.mkdir(parents=True, exist_ok=True)

    rendered: dict[int, Path] = {}
    if render_mode != "none":
        selected_pages: set[int] | None
        if render_mode == "all":
            selected_pages = None
        else:
            selected_pages = {
                index
                for index, original in enumerate(pages, start=1)
                if page_status(normalize_text(original))[0] == "OCR_CANDIDATE"
            }

        if render_mode == "all" or selected_pages:
            try:
                image_dir = args.out_dir / f"{pdf.stem}_images"
                rendered = render_pages(pdf, image_dir, args.dpi, selected_pages)
            except Exception as exc:
                print(f"error: {exc}", file=sys.stderr)
                return 3

    raw, results = build_raw(pdf, pages, rendered, args.out_dir)
    report = build_report(pdf, extractor_name, results, render_mode, args.dpi)

    stem = pdf.stem
    raw_path = args.out_dir / f"{stem}_raw.md"
    report_path = args.out_dir / f"{stem}_extraction_report.md"
    raw_path.write_text(raw, encoding="utf-8")
    report_path.write_text(report, encoding="utf-8")

    summary = {
        "pdf": str(pdf),
        "extractor": extractor_name,
        "raw": str(raw_path),
        "report": str(report_path),
        "pages": len(results),
        "render_mode": render_mode,
        "rendered_images": [str(rendered[p]) for p in sorted(rendered)],
        "ocr_candidates": [r.page for r in results if r.status == "OCR_CANDIDATE"],
    }
    if args.json:
        print(json.dumps(summary, ensure_ascii=False, indent=2))
    else:
        print(f"raw: {raw_path}")
        print(f"report: {report_path}")
        if summary["rendered_images"]:
            print(f"rendered images: {len(summary['rendered_images'])}")
        if summary["ocr_candidates"]:
            print("OCR candidates:", ", ".join(map(str, summary["ocr_candidates"])))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
